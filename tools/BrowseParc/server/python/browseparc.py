def _build_command(action, params, events_path):
    """Translate the web request into medulla-deploy-agent.sh arguments."""
    cmd = [DEPLOY_SCRIPT]
    mode = (params.get("mode") or "network").strip()
    port = _validate_port(params.get("port", 5985)) or 5985
    namefilter = (params.get("namefilter") or "").strip()
    username = (params.get("username") or "").strip()
    password = params.get("password") or ""
    domain = (params.get("domain") or "").strip()
    sshkey = (params.get("sshkey") or "").strip()
    timeout = _validate_timeout(params.get("timeout"))

    if action == ACTION_PREREQ:
        return [DEPLOY_SCRIPT, "--check-prereq", "--json", "--non-interactive"]

    if action == ACTION_UUID_LOOKUP:
        # The host list is written to hosts.txt and fed on stdin.
        return [DEPLOY_SCRIPT, "--uuid-lookup", "--json", "--non-interactive"]

    if action == ACTION_PS_SETUP:
        return [DEPLOY_SCRIPT, "--ps-setup", "--json", "--non-interactive"]

    if namefilter and not re.match(r"^[A-Za-z0-9._-]{1,64}$", namefilter):
        raise ValueError("Invalid name filter")

    if action == ACTION_LIST_OUS:
        server = _validate_host(params.get("server"))
        if not server:
            raise ValueError("An Active Directory server is required")
        if not username or not password:
            raise ValueError("A user name and a password are required for Active Directory")
        cmd += ["--server=%s" % server, "--list-ous"]
    elif action == ACTION_DISCOVER:
        if mode == "ad":
            server = _validate_host(params.get("server"))
            if not server:
                raise ValueError("An Active Directory server is required")
            if not username or not password:
                raise ValueError("A user name and a password are required for Active Directory")
            cmd += ["--server=%s" % server]
            if domain:
                cmd += ["--domain=%s" % domain]
        else:
            target = _validate_target(params.get("target"))
            if not target:
                raise ValueError(_target_error(params.get("target"))
                                 or "A network (CIDR) or a machine is required")
            cmd += ["--target=%s" % target]
        ou = (params.get("ou") or "").strip()
        if ou:
            if not RE_OU.match(ou):
                raise ValueError("Invalid organizational unit")
            cmd += ["--ou=%s" % ou]
        cmd += ["--port=%d" % port, "--discover"]
    elif action == ACTION_INSTALL:
        targets = params.get("targets") or []
        if isinstance(targets, str):
            targets = [item for item in targets.split(",")]
        clean = []
        details = []
        for item in targets:
            # Accepts both whole machine objects (web interface) and plain names.
            host, osys, ports = _target_details(item)
            if not host:
                raise ValueError("Invalid machine: %s" % item)
            if host in clean:
                continue
            clean.append(host)
            if osys or ports:
                details.append({"target": host, "os": osys, "ports": ports,
                                "method": _install_transport(osys, ports) or ""})
        if not clean:
            raise ValueError("No machine selected")
        if len(clean) > 512:
            raise ValueError("Too many machines selected (512 maximum)")
        cmd += ["--targets=%s" % ",".join(clean), "--port=%d" % port]
        if details:
            # Lets the script pick the right transport per machine instead of
            # relying on a single port typed in the form.
            cmd += ["--target-info=%s" % json.dumps(details, separators=(",", ":"))]
        if params.get("agent_insecure"):
            cmd += ["--agent-win-insecure"]
        agent_options = _resolve_agent(params.get("agent_id"))
        agent_options.update(_linux_download_options(params.get("agent_id")))
        for option, value in sorted(agent_options.items()):
            cmd += ["%s=%s" % (option, value)]
        if sshkey:
            if not re.match(r"^/[A-Za-z0-9._/-]{1,255}$", sshkey):
                raise ValueError("Invalid ssh key path")
            cmd += ["--sshkey=%s" % sshkey]
        if params.get("reinstall"):
            cmd += ["--reinstall"]
        if timeout:
            cmd += ["--timeout=%d" % timeout]
    else:
        raise ValueError("Unsupported action")

    if namefilter:
        cmd += ["--namefilter=%s" % namefilter]

    # Credentials: the password travels through the environment only.
    if username:
        if not RE_USERNAME.match(username):
            raise ValueError("Invalid user name")
        cmd += ["--username=%s" % username]
        cmd += ["--password-env=%s" % PASSWORD_ENV]

    cmd += ["--json", "--non-interactive", "--skip-ps-setup", "--state-file=%s" % events_path]
    return cmd


_LAST_PURGE = 0.0


def _purge_jobs(force=False):
    """Remove old finished jobs (age and count limits, both configurable)."""
    global _LAST_PURGE
    now = time.time()
    with _LOCK:
        if not force and now - _LAST_PURGE < JOB_PURGE_INTERVAL:
            return 0
        _LAST_PURGE = now
    max_age = _config_int("job_retention_days", JOB_RETENTION_DAYS, 1, 3650) * 86400
    max_count = _config_int("job_retention_max", JOB_RETENTION_MAX, 10, 100000)
    entries = []
    for jobdir in glob.glob(os.path.join(JOBS_DIR, "*")):
        job_id = os.path.basename(jobdir)
        if not RE_JOBID.match(job_id) or not os.path.isdir(jobdir):
            continue
        try:
            entries.append((os.path.getmtime(jobdir), job_id, jobdir))
        except OSError:
            continue
    entries.sort(reverse=True)
    removed = 0
    for index, (mtime, job_id, jobdir) in enumerate(entries):
        if index < max_count and now - mtime < max_age:
            continue
        if _pid_alive(_read_pid(jobdir), job_id):
            continue
        shutil.rmtree(jobdir, ignore_errors=True)
        with _LOCK:
            _EVENTS_CACHE.pop(os.path.join(jobdir, "events.jsonl"), None)
            _CHILDREN.pop(job_id, None)
        removed += 1
    if removed:
        logger.info("browseparc: %d old job(s) removed", removed)
    return removed


def browse_parc_start(params):
    """Start a discovery / deployment / prerequisite job. Returns the job id."""
    try:
        params = params or {}
        action = (params.get("action") or "").strip()
        if action not in (ACTION_DISCOVER, ACTION_INSTALL, ACTION_LIST_OUS,
                          ACTION_PS_SETUP, ACTION_PREREQ, ACTION_UUID_LOOKUP):
            return {"ok": False, "error": "Unsupported action"}

        if not os.path.isfile(DEPLOY_SCRIPT) or not os.access(DEPLOY_SCRIPT, os.X_OK):
            return {"ok": False, "error": "%s is missing or not executable" % DEPLOY_SCRIPT}

        _ensure_dirs()
        _purge_jobs()

        with _LOCK:
            return _start_locked(action, params)
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot start the job")
        return {"ok": False, "error": str(exc)}


def _start_locked(action, params):
    # Serialised: the "too many jobs" check and the spawn must not interleave
    # between two requests, or the limit could be exceeded.
    try:
        if action in (ACTION_DISCOVER, ACTION_INSTALL, ACTION_LIST_OUS,
                      ACTION_UUID_LOOKUP) and _running_jobs() >= MAX_RUNNING_JOBS:
            return {"ok": False, "error": "Too many jobs are already running, please wait"}

        job_id = time.strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:8]
        jobdir = os.path.join(JOBS_DIR, job_id)
        os.makedirs(jobdir, mode=0o700)

        events_path = os.path.join(jobdir, "events.jsonl")
        try:
            cmd = _build_command(action, params, events_path)
        except ValueError as exc:
            shutil.rmtree(jobdir, ignore_errors=True)
            return {"ok": False, "error": str(exc)}

        # The request is kept for the audit trail, the password is not.
        request = {key: value for key, value in params.items() if key != "password"}
        if "group" in request:
            request["group"] = str(request["group"]).strip()[:128]
        request["action"] = action
        request["credential_provided"] = bool(params.get("password"))
        request["command"] = [item for item in cmd if not item.startswith("--password")]
        with open(os.path.join(jobdir, "request.json"), "w") as handle:
            json.dump(request, handle, indent=2)

        stdin = subprocess.DEVNULL
        if action == ACTION_UUID_LOOKUP:
            hosts = params.get("targets") or []
            if isinstance(hosts, str):
                hosts = [item for item in hosts.split(",")]
            clean_hosts = []
            for item in hosts:
                host = _validate_host(item)
                if host and host not in clean_hosts:
                    clean_hosts.append(host)
            if not clean_hosts:
                shutil.rmtree(jobdir, ignore_errors=True)
                return {"ok": False, "error": "No machine given"}
            if len(clean_hosts) > 512:
                shutil.rmtree(jobdir, ignore_errors=True)
                return {"ok": False, "error": "Too many machines (512 maximum)"}
            hosts_path = os.path.join(jobdir, "hosts.txt")
            with open(hosts_path, "w") as handle:
                handle.write("\n".join(clean_hosts) + "\n")
            stdin = open(hosts_path, "rb")

        stdout = open(os.path.join(jobdir, "stdout.log"), "wb")
        stderr = open(os.path.join(jobdir, "stderr.log"), "wb")

        env = os.environ.copy()
        password = params.get("password") or ""
        if password:
            env[PASSWORD_ENV] = password

        proc = subprocess.Popen(
            cmd,
            stdin=stdin,
            stdout=stdout,
            stderr=stderr,
            env=env,
            cwd=jobdir,
            start_new_session=True,
            close_fds=True,
        )
        stdout.close()
        stderr.close()
        if stdin is not subprocess.DEVNULL:
            stdin.close()

        with open(os.path.join(jobdir, "pid"), "w") as handle:
            handle.write(str(proc.pid))
        with open(os.path.join(jobdir, "started"), "w") as handle:
            handle.write(str(int(time.time())))

        _register_child(job_id, proc)

        logger.info("browseparc: job %s started (%s)", job_id, action)
        return {"ok": True, "job": job_id, "action": action}
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot start the job")
        return {"ok": False, "error": str(exc)}


def browse_parc_status(job_id, log_offset=0, with_log=True):
    """Aggregate the state of a job for the web interface.

    with_log=False skips the log read (callers that only need the result).
    """
    try:
        job_id = (job_id or "").strip()
        if not RE_JOBID.match(job_id):
            return {"ok": False, "error": "Invalid job identifier"}
        jobdir = os.path.join(JOBS_DIR, job_id)
        if not os.path.isdir(jobdir):
            return {"ok": False, "error": "Unknown job"}

        log_offset = _as_int(log_offset)
        if log_offset < 0:
            log_offset = 0

        events = _read_events(jobdir)
        state = {
            "job": job_id,
            "mode": None,
            "status": "pending",
            "progress": {"done": 0, "total": 0},
            "machines": [],
            "ous": [],
            "uuids": {},
            "prerequisites": None,
            "results": [],
            "summary": {},
            "error": None,
            "started": None,
            "finished": False,
        }
        for event in events:
            kind = event.get("event")
            if kind == "start":
                state["mode"] = event.get("mode") or state["mode"]
                state["progress"]["total"] = event.get("total") or state["progress"]["total"]
            elif kind == "machine":
                machine = event.get("machine") or {}
                if machine:
                    state["machines"].append(machine)
            elif kind == "ou":
                # The tree is rebuilt in the browser from `parent`; `machines` is
                # what the unit holds directly, `total` what it holds including
                # its sub units (only the branches with machines are sent).
                state["ous"].append({
                    "name": event.get("name") or "",
                    "dn": event.get("dn") or "",
                    "canonical": event.get("canonical") or "",
                    "kind": event.get("kind") or "ou",
                    "machines": _as_int(event.get("machines")),
                    "total": _as_int(event.get("total")),
                    "parent": event.get("parent") or "",
                })
            elif kind == "machine_uuid":
                state["uuids"][event.get("host") or ""] = {
                    "hostname": event.get("hostname") or "",
                    "uuid": event.get("uuid") or "",
                    "jid": event.get("jid") or "",
                    "known": bool(event.get("known")),
                }
            elif kind == "progress":
                state["progress"]["done"] = event.get("done") or state["progress"]["done"]
                state["progress"]["total"] = event.get("total") or state["progress"]["total"]
            elif kind == "error":
                state["error"] = event.get("message") or "Unknown error"
            elif kind == "end":
                state["finished"] = True
                state["summary"] = {
                    "status": event.get("status"),
                    "total": event.get("total"),
                    "ok": event.get("ok"),
                    "ko": event.get("ko"),
                    "results": event.get("results") or [],
                }

        try:
            with open(os.path.join(jobdir, "started"), "r") as handle:
                state["started"] = int(handle.read().strip() or 0)
        except (OSError, ValueError):
            state["started"] = None

        _reap_children()
        pid = _read_pid(jobdir)
        alive = _pid_alive(pid, job_id)
        final = None
        if not alive:
            final = _final_json(jobdir)

        # A cancellation wins over the process state: the child may still be
        # terminating when the browser asks for the status.
        cancelled = os.path.isfile(os.path.join(jobdir, "cancelled"))
        if cancelled:
            state["status"] = "cancelled"
            state["error"] = None
        elif alive:
            state["status"] = "running"
        elif state["error"]:
            state["status"] = "error"
        elif final and final.get("status") == "error":
            state["status"] = "error"
            state["error"] = final.get("message") or state["error"]
        elif state["finished"] or final:
            state["status"] = "done"
        else:
            state["status"] = "error"
            if not state["error"]:
                state["error"] = "The job stopped unexpectedly, check the server logs"

        if final:
            if final.get("mode"):
                state["mode"] = final["mode"]
            final_machines = final.get("machines")
            # discover answers with a list, uuid-lookup with a dict keyed by host
            if final_machines and isinstance(final_machines, list):
                state["machines"] = final_machines
            if final.get("ous"):
                state["ous"] = final["ous"]
            if final.get("results"):
                state["summary"]["results"] = final["results"]
            if final_machines and isinstance(final_machines, dict):
                for host, info in final_machines.items():
                    if not isinstance(info, dict):
                        continue
                    state["uuids"][host] = {
                        "hostname": info.get("hostname") or "",
                        "uuid": info.get("uuid") or "",
                        "jid": info.get("jid") or "",
                        "known": bool(info.get("known")),
                    }
            if final.get("prerequisites"):
                state["prerequisites"] = final["prerequisites"]
            for key in ("total", "ok", "ko", "message"):
                if final.get(key) is not None:
                    state["summary"][key] = final[key]

        if state["progress"]["total"] == 0:
            state["progress"]["total"] = len(state["machines"]) or len(state["ous"])

        if with_log:
            lines, new_offset, more, truncated = _read_log_chunk(
                os.path.join(jobdir, "stderr.log"), log_offset, complete_only=alive)
        else:
            lines, new_offset, more, truncated = [], log_offset, False, False
        state["log"] = lines
        state["log_offset"] = new_offset
        state["log_more"] = more
        state["log_truncated"] = truncated

        request = _read_json_file(os.path.join(jobdir, "request.json")) or {}
        state["request"] = {
            "action": request.get("action"),
            "mode": request.get("mode"),
            "target": request.get("target"),
            "server": request.get("server"),
            "ou": request.get("ou"),
            "namefilter": request.get("namefilter"),
            "targets": request.get("targets"),
        }
        state["ok"] = True
        return _xml_safe(state)
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot read the job status")
        return {"ok": False, "error": str(exc)}


def browse_parc_cancel(job_id):
    """Stop a running job."""
    try:
        job_id = (job_id or "").strip()
        if not RE_JOBID.match(job_id):
            return {"ok": False, "error": "Invalid job identifier"}
        jobdir = os.path.join(JOBS_DIR, job_id)
        if not os.path.isdir(jobdir):
            return {"ok": False, "error": "Unknown job"}
        pid = _read_pid(jobdir)
        if not _pid_alive(pid, job_id):
            return {"ok": True, "cancelled": False, "message": "The job is not running anymore"}
        try:
            os.killpg(os.getpgid(pid), 15)
        except OSError:
            try:
                os.kill(pid, 15)
            except OSError as exc:
                return {"ok": False, "error": str(exc)}
        # Remember the cancellation so the status reports "cancelled" instead of
        # an unexpected stop.
        try:
            with open(os.path.join(jobdir, "cancelled"), "w") as handle:
                handle.write(str(int(time.time())))
        except OSError:
            pass
        return {"ok": True, "cancelled": True}
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot cancel the job")
        return {"ok": False, "error": str(exc)}


def browse_parc_jobs(limit=10, group=None):
    """Last jobs, most recent first. With a group name: the installations
    started from that agent installation group only."""
    try:
        _ensure_dirs()
        try:
            limit = max(1, min(int(limit), 50))
        except (TypeError, ValueError):
            limit = 10
        _reap_children()
        entries = []
        for jobdir in glob.glob(os.path.join(JOBS_DIR, "*")):
            if not os.path.isdir(jobdir):
                continue
            try:
                mtime = os.path.getmtime(jobdir)
            except OSError:
                continue
            entries.append((mtime, os.path.basename(jobdir)))
        entries.sort(reverse=True)
        jobs = []
        group = str(group) if group else ""
        for _, job_id in entries:
            if len(jobs) >= limit:
                break
            jobdir = os.path.join(JOBS_DIR, job_id)
            pid = _read_pid(jobdir)
            request = _read_json_file(os.path.join(jobdir, "request.json")) or {}
            if group and (request.get("action") != ACTION_INSTALL
                          or request.get("group") != group):
                continue
            events = _read_events(jobdir)
            total = 0
            ended = ""
            for event in events:
                if event.get("event") == "start":
                    total = event.get("total") or total
                elif event.get("event") == "end":
                    ended = event.get("status") or ""
            # A stopped job must not read as "finished": the table showed "done"
            # after a cancellation, which looked like the job had gone through.
            # The cancellation marker wins over the process state, as in
            # browse_parc_status: the child may still be terminating when the
            # table is refreshed, and the row must switch at once.
            if os.path.exists(os.path.join(jobdir, "cancelled")):
                state = "cancelled"
            elif _pid_alive(pid, job_id):
                state = "running"
            elif ended == "error":
                state = "error"
            else:
                state = "finished"
            jobs.append({
                "job": job_id,
                "action": request.get("action"),
                "mode": request.get("mode"),
                "target": request.get("target") or request.get("server") or "",
                "group": request.get("group") or "",
                "state": state,
                "total": total,
            })
        return {"ok": True, "jobs": jobs}
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot list the jobs")
        return {"ok": False, "error": str(exc)}


def browse_parc_machine_log(job_id, target):
    """Log of one machine of an installation job (every task and the error)."""
    try:
        job_id = (job_id or "").strip()
        if not RE_JOBID.match(job_id):
            return {"ok": False, "error": "Invalid job identifier"}
        target = (target or "").strip()
        if not target or len(target) > 300:
            return {"ok": False, "error": "Invalid machine"}
        safe = re.sub(r"[^A-Za-z0-9._-]", "_", target)[:120]
        path = os.path.join(JOBS_DIR, job_id, "logs", safe + ".log")
        try:
            size = os.path.getsize(path)
            with open(path, "rb") as handle:
                if size > MAX_MACHINE_LOG:
                    handle.seek(size - MAX_MACHINE_LOG)
                data = handle.read(MAX_MACHINE_LOG)
        except OSError:
            return {"ok": False, "error": "No log for this machine"}
        text = RE_ANSI.sub("", data.decode("utf-8", "replace"))
        return _xml_safe({"ok": True, "target": target, "log": text,
                          "truncated": size > MAX_MACHINE_LOG})
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot read the machine log")
        return {"ok": False, "error": str(exc)}


def _spawn_prereq_refresh():
    """Refresh the cached prerequisite report without ever blocking the agent."""
    _ensure_dirs()
    cache = _prereq_cache()
    tmp = cache + ".tmp"
    # "timeout" (GNU coreutils) is present on the Medulla servers, but the code
    # must not depend on it being installed.
    watchdog = "timeout 120 " if shutil.which("timeout") else ""
    # Only fixed paths and a constant option list are interpolated here.
    command = (
        "%s%s --check-prereq --json --non-interactive > %s 2>/dev/null "
        "&& mv %s %s" % (watchdog, DEPLOY_SCRIPT, tmp, tmp, cache)
    )
    try:
        subprocess.Popen(
            ["/bin/sh", "-c", command],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
            close_fds=True,
        )
    except OSError:
        logger.exception("browseparc: cannot refresh the prerequisites")


def browse_parc_prerequisites(force=False):
    """Prerequisite report, served from a cache refreshed in the background.

    This method must stay non blocking: with multithreading disabled the
    mmc-agent executes plugin methods inside the Twisted reactor, so waiting for
    pwsh here would freeze the whole MMC for every user.
    """
    global _PREREQ_LAST_REFRESH
    try:
        _ensure_dirs()
        cache = _prereq_cache()
        cached = _read_json_file(cache)
        now = time.time()
        checked_at = 0.0
        if os.path.isfile(cache):
            try:
                checked_at = os.path.getmtime(cache)
            except OSError:
                checked_at = 0.0
        fresh = bool(cached) and (now - checked_at) < PREREQ_TTL
        refreshing = False
        with _LOCK:
            due = (force or not fresh) and (now - _PREREQ_LAST_REFRESH) > 20
            if due:
                _PREREQ_LAST_REFRESH = now
        if due:
            _spawn_prereq_refresh()
            refreshing = True
        return {
            "ok": True,
            "prerequisites": (cached or {}).get("prerequisites") or {},
            "cached": bool(cached),
            "checked_at": int(checked_at) if checked_at else None,
            "refreshing": refreshing,
        }
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot read the prerequisites")
        return {"ok": False, "error": str(exc)}



def _valid_ipv4(value):
    parts = value.split(".")
    if len(parts) != 4:
        return False
    for part in parts:
        if not part.isdigit() or not 0 <= int(part) <= 255:
            return False
    return True


def _min_cidr_prefix():
    return _config_int("min_cidr_prefix", MIN_CIDR_PREFIX, 8, 32)


def _target_error(value):
    """Explicit reason why a discovery target is refused (None if it is fine)."""
    value = (value or "").strip()
    match = RE_CIDR.match(value)
    if match and _valid_ipv4(value.split("/")[0]):
        minimum = _min_cidr_prefix()
        if int(match.group(5)) < minimum:
            return "Network too large: use a /%d prefix or longer" % minimum
    return None


def _validate_target(value):
    """CIDR network, IPv4 address or host name."""
    value = (value or "").strip()
    if not value or len(value) > 255:
        return None
    if RE_CIDR.match(value):
        address, prefix = value.split("/")
        if _valid_ipv4(address) and _min_cidr_prefix() <= int(prefix) <= 32:
            return value
        return None
    if RE_IPV4.match(value):
        return value if _valid_ipv4(value) else None
    if RE_HOSTNAME.match(value) and not value.startswith("-") and ".." not in value:
        return value
    return None


def _validate_host(value):
    """Single machine: IPv4 address or host name (no CIDR)."""
    value = (value or "").strip()
    if not value or len(value) > 255:
        return None
    if RE_IPV4.match(value):
        return value if _valid_ipv4(value) else None
    if RE_HOSTNAME.match(value) and ".." not in value:
        return value
    return None


def _validate_port(value):
    try:
        port = int(value)
    except (TypeError, ValueError):
        return None
    return port if 1 <= port <= 65535 else None


def _validate_timeout(value):
    try:
        timeout = int(value)
    except (TypeError, ValueError):
        return None
    return timeout if 5 <= timeout <= 7200 else None


def _validate_group_name(value):
    value = (value or "").strip()
    if not RE_GROUPNAME.match(value):
        return None
    if value in (".", ".."):
        return None
    return value


def _group_path(name):
    return os.path.join(GROUPS_DIR, "%s.json" % name)


# events.jsonl is append-only: each poll only parses what was added since the
# previous one instead of the whole file.
_EVENTS_CACHE = {}
EVENTS_CACHE_MAX = 64


def _parse_event(line):
    line = line.strip()
    if not line:
        return None
    try:
        return _xml_safe(json.loads(line))
    except ValueError:
        return None


def _read_events(jobdir):
    path = os.path.join(jobdir, "events.jsonl")
    try:
        stat = os.stat(path)
    except OSError:
        with _LOCK:
            _EVENTS_CACHE.pop(path, None)
        return []
    with _LOCK:
        entry = _EVENTS_CACHE.pop(path, None)
        if entry is None or entry["ino"] != stat.st_ino or stat.st_size < entry["pos"]:
            entry = {"ino": stat.st_ino, "pos": 0, "events": []}
        try:
            with open(path, "rb") as handle:
                handle.seek(entry["pos"])
                data = handle.read()
        except OSError:
            data = b""
        tail = []
        if data:
            complete, _, partial = data.rpartition(b"\n")
            if complete or data.endswith(b"\n"):
                for line in complete.decode("utf-8", "replace").split("\n"):
                    event = _parse_event(line)
                    if event is not None:
                        entry["events"].append(event)
                entry["pos"] += len(complete) + 1
            # A last line without its newline may still be in the middle of
            # being written: use it when it is valid, but do not consume it.
            event = _parse_event(partial.decode("utf-8", "replace"))
            if event is not None:
                tail.append(event)
        _EVENTS_CACHE[path] = entry
        while len(_EVENTS_CACHE) > EVENTS_CACHE_MAX:
            _EVENTS_CACHE.pop(next(iter(_EVENTS_CACHE)))
        return list(entry["events"]) + tail


def _read_json_file(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            return _xml_safe(json.load(handle))
    except (OSError, ValueError):
        return None


# XML 1.0 forbids most control characters (0x00-0x08, 0x0B, 0x0C, 0x0E-0x1F).
# They are valid UTF-8, so a log line carrying an ANSI colour escape sequence
# makes the XML-RPC serialisation produce an invalid document: the PHP client
# then fails to decode it and the interface sees an empty answer.
RE_XML_ILLEGAL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")
RE_ANSI = re.compile(r"\x1b\[[0-9;?]*[ -/]*[@-~]")


def _xml_safe(value):
    """Strip ANSI sequences and characters that XML 1.0 does not allow."""
    if isinstance(value, str):
        return RE_XML_ILLEGAL.sub("", RE_ANSI.sub("", value))
    if isinstance(value, dict):
        return {_xml_safe(k): _xml_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_xml_safe(item) for item in value]
    return value


def _as_int(value, default=0):
    """Best effort integer: the agent may answer with strings or lists."""
    if isinstance(value, (list, tuple)):
        value = value[0] if value else default
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def _tail_lines(path, limit=MAX_LOG_LINES):
    if not os.path.isfile(path):
        return []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            lines = handle.read().splitlines()
    except OSError:
        return []
    return [_xml_safe(line) for line in lines[-limit:]]


def _read_log_chunk(path, offset, complete_only=True):
    """Read at most MAX_LOG_CHUNK bytes of a log from a byte offset.

    Returns (lines, new_offset, more, truncated). Only whole lines are
    returned while the job runs, so a line being written is never cut in two.
    `more` tells the caller that data is still waiting (poll again at once).
    A first read of a huge log starts from its tail (truncated=True).
    """
    try:
        size = os.path.getsize(path)
    except OSError:
        return [], 0, False, False
    truncated = False
    if offset < 0 or offset > size:
        offset = 0
    if offset == 0 and size > MAX_LOG_CHUNK:
        offset = size - MAX_LOG_CHUNK
        truncated = True
    try:
        with open(path, "rb") as handle:
            handle.seek(offset)
            data = handle.read(MAX_LOG_CHUNK)
    except OSError:
        return [], offset, False, False
    if truncated:
        cut = data.find(b"\n")
        if cut >= 0:
            offset += cut + 1
            data = data[cut + 1:]
    end_reached = offset + len(data) >= size
    if complete_only and data and not data.endswith(b"\n"):
        cut = data.rfind(b"\n")
        if cut >= 0:
            data = data[:cut + 1]
        elif end_reached:
            # one unfinished line: wait for its end
            data = b""
        # else: a single line longer than the chunk, hand it over as is
    new_offset = offset + len(data)
    lines = [_xml_safe(line) for line in data.decode("utf-8", "replace").splitlines()]
    return lines, new_offset, new_offset < size and bool(data), truncated


# Popen objects of the jobs started by this agent process. Keeping them lets
# us reap the finished children instead of leaving zombies behind.
_CHILDREN = {}


def _register_child(job_id, proc):
    with _LOCK:
        _CHILDREN[job_id] = proc


def _reap_children():
    with _LOCK:
        for job_id, proc in list(_CHILDREN.items()):
            try:
                if proc.poll() is not None:
                    _CHILDREN.pop(job_id, None)
            except Exception:
                _CHILDREN.pop(job_id, None)


def _pid_alive(pid, job_id=None):
    """A finished but not yet reaped child is a zombie: kill(pid, 0) lies."""
    if not pid:
        return False
    if job_id is not None:
        with _LOCK:
            proc = _CHILDREN.get(job_id)
        if proc is not None:
            try:
                return proc.poll() is None
            except Exception:
                pass
    try:
        with open("/proc/%d/stat" % pid, "rb") as handle:
            data = handle.read().decode("utf-8", "replace")
    except OSError:
        return False
    try:
        state = data.rsplit(")", 1)[1].split()[0]
    except IndexError:
        return False
    return state != "Z"


def _running_jobs():
    _reap_children()
    running = 0
    for jobdir in glob.glob(os.path.join(JOBS_DIR, "*")):
        pid = _read_pid(jobdir)
        if _pid_alive(pid, os.path.basename(jobdir)):
            running += 1
    return running


def _read_pid(jobdir):
    try:
        with open(os.path.join(jobdir, "pid"), "r") as handle:
            raw = handle.read().strip()
    except OSError:
        return None
    if not RE_PID.match(raw):
        return None
    return int(raw)


def _final_json(jobdir):
    """Last complete JSON object printed by the script on its stdout."""
    lines = _tail_lines(os.path.join(jobdir, "stdout.log"), 50)
    for line in reversed(lines):
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            return json.loads(line)
        except ValueError:
            continue
    return None



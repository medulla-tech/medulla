def _normalize_machines(machines):
    clean = []
    if not isinstance(machines, list):
        return clean
    for item in machines:
        if isinstance(item, str):
            host = _validate_host(item)
            if host:
                clean.append({"target": host, "name": host, "ip": "", "source": "", "ou": "", "os": ""})
            continue
        if not isinstance(item, dict):
            continue
        target = _validate_host(item.get("target") or item.get("name"))
        if not target:
            continue
        # ports and services are what the installation (SSH or WinRM) and the
        # remote control buttons are derived from: a group that forgot them
        # would deploy differently from the selection it was made from.
        _host, _osys, ports = _target_details(item)
        services = []
        raw_services = item.get("services")
        if isinstance(raw_services, list):
            for value in raw_services[:16]:
                if isinstance(value, str) and re.match(r"^[a-z0-9_-]{1,16}$", value) \
                        and value not in services:
                    services.append(value)
        clean.append({
            "target": target,
            "name": (item.get("name") or target)[:255],
            "ip": (item.get("ip") or "")[:45],
            "source": (item.get("source") or "")[:32],
            "ou": (item.get("ou") or "")[:500],
            "os": (item.get("os") or "")[:128],
            "ports": ports[:32],
            "services": services,
        })
    # deduplicate, keep the order
    seen = set()
    unique = []
    for machine in clean:
        if machine["target"] in seen:
            continue
        seen.add(machine["target"])
        unique.append(machine)
    return unique



def browse_parc_group_save(name, machines, description=""):
    """Create or replace a targeting group."""
    try:
        _ensure_dirs()
        name = _validate_group_name(name)
        if not name:
            return {"ok": False, "error": "Invalid group name"}
        clean = _normalize_machines(machines)
        if not clean:
            return {"ok": False, "error": "The group must contain at least one machine"}

        path = _group_path(name)
        existing = _read_json_file(path)
        now = time.strftime("%Y-%m-%d %H:%M:%S")
        payload = {
            "name": name,
            "description": (description or "")[:500],
            "created": (existing or {}).get("created") or now,
            "updated": now,
            "machines": clean,
        }
        with _LOCK:
            # Unique temporary file: two saves of the same group must not
            # write into the same one.
            fd, tmp = tempfile.mkstemp(prefix=".%s." % name, suffix=".tmp", dir=GROUPS_DIR)
            try:
                with os.fdopen(fd, "w") as handle:
                    json.dump(payload, handle, indent=2)
                os.chmod(tmp, 0o600)
                os.replace(tmp, path)
            except Exception:
                try:
                    os.remove(tmp)
                except OSError:
                    pass
                raise
        return {"ok": True, "group": name, "count": len(clean),
                "replaced": bool(existing)}
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("browseparc: cannot save the group")
        return {"ok": False, "error": str(exc)}



def _config_value(option, default=None):
    """Optional setting of the [browseparc] section of the admin plugin."""
    parser = configparser.ConfigParser(interpolation=None)
    try:
        parser.read(list(BP_CONFIG_FILES), encoding="utf-8")
    except configparser.Error:
        return default
    if parser.has_option("browseparc", option):
        return parser.get("browseparc", option).strip()
    return default


def _config_int(option, default, low, high):
    try:
        value = int(_config_value(option, default))
    except (TypeError, ValueError):
        return default
    return value if low <= value <= high else default


def _key_dirs():
    """Real paths of the directories a private key may be read from."""
    configured = _config_value("ssh_key_dirs")
    if configured is not None:
        patterns = [item.strip() for item in configured.split(",")]
    else:
        patterns = list(GUAC_KEY_DIRS)
    allowed = []
    for pattern in patterns:
        if pattern.startswith("/"):
            allowed.extend(os.path.realpath(match) for match in glob.glob(pattern))
    return allowed


def _guacamole_settings():
    """Base URL, web credentials and API endpoint of the Guacamole webapp."""
    template = None
    for path in GUAC_XMPP_INI:
        if not os.path.isfile(path):
            continue
        parser = configparser.ConfigParser(interpolation=None)
        try:
            parser.read(path)
        except configparser.Error:
            continue
        for section in parser.sections():
            if parser.has_option(section, "guacamole_baseurl"):
                template = parser.get(section, "guacamole_baseurl")
    if not template:
        raise ValueError("guacamole_baseurl is not configured")

    credentials = {}
    if "?" in template:
        credentials = urllib.parse.parse_qs(template.split("?", 1)[1])
    username = (credentials.get("username") or [""])[0]
    password = (credentials.get("password") or [""])[0]
    if not username or not password:
        raise ValueError("guacamole_baseurl does not carry any credential")

    # The API is called on the loopback: Apache restricts /guacamole/ to
    # requests carrying a Medulla Referer.
    path = urllib.parse.urlparse(template).path.rstrip("/") or "/guacamole"
    return {
        "template": template,
        "username": username,
        "password": password,
        "api": "https://127.0.0.1" + path,
        "data_source": "mysql",
    }


def _probe_rdp_security(host, port, timeout=GUAC_RDP_PROBE_TIMEOUT):
    """Ask an RDP server which security protocol it selects.

    Returns (selected, failure, error):

    * ``selected``: the protocol chosen by an RDP_NEG_RSP (0 = standard RDP
      security, 1 = TLS, 2 = NLA, 8 = all);
    * ``failure``: the code of an RDP_NEG_FAILURE. Code 2
      (SSL_NOT_ALLOWED_BY_SERVER) means the server only accepts **standard RDP
      security**, exactly like ``selected == 0``: that is not a broken service;
    * ``error``: transport level problem, when nothing could be read.

    This probe is advisory only: callers must never refuse a session because of
    it, the Guacamole client is the authority.
    """
    import socket
    import struct

    request = (b"\x03\x00\x00\x13"          # TPKT, 19 bytes
               b"\x0e\xe0\x00\x00\x00\x00\x00"  # X.224 Connection Request
               b"\x01\x00\x08\x00"          # RDP_NEG_REQ
               b"\x0b\x00\x00\x00")          # ask for everything we support

    try:
        with socket.create_connection((host, int(port)), timeout=timeout) as sock:
            sock.settimeout(timeout)
            sock.send(request)
            data = b""
            while len(data) < 4:
                chunk = sock.recv(4 - len(data))
                if not chunk:
                    break
                data += chunk
            if len(data) < 4:
                return None, None, "no answer"
            length = struct.unpack(">H", data[2:4])[0]
            while len(data) < length:
                chunk = sock.recv(length - len(data))
                if not chunk:
                    break
                data += chunk
    except OSError as exc:
        return None, None, str(exc)

    # type(1) flags(1) length(2, little endian) value(4)
    for index in range(max(0, len(data) - 7)):
        if data[index + 2:index + 4] != b"\x08\x00":
            continue
        value = struct.unpack("<I", data[index + 4:index + 8])[0]
        if data[index] == 0x02:      # RDP_NEG_RSP
            return value, None, None
        if data[index] == 0x03:      # RDP_NEG_FAILURE
            return None, value, None
    return None, None, "unexpected answer"


def _relay_ssh_keyfile():
    """Private key configured for the Medulla relay, if any."""
    if not os.path.isfile(GUAC_RELAY_INI):
        return ""
    parser = configparser.ConfigParser(interpolation=None)
    try:
        parser.read(GUAC_RELAY_INI)
    except configparser.Error:
        return ""
    if parser.has_section("parameters") and parser.has_option("parameters", "ssh_keyfile"):
        return parser.get("parameters", "ssh_keyfile").strip()
    return ""


def _read_private_key(path):
    """Read a private key, restricted to the directories we accept.

    Returns (content, error). The path is resolved first so that a symbolic
    link cannot be used to escape the allowed directories.
    """
    path = (path or "").strip()
    if not path or not path.startswith("/"):
        return None, "Invalid SSH key path"

    real = os.path.realpath(path)
    if not any(real.startswith(base + os.sep) for base in _key_dirs()):
        return None, "SSH key must live in an allowed directory (/root/.ssh or /home/*/.ssh)"

    if not os.path.isfile(real):
        return None, "SSH key not found"

    try:
        with open(real, "r", encoding="utf-8", errors="replace") as handle:
            content = handle.read()
    except OSError as exc:
        return None, "Cannot read the SSH key: %s" % exc

    if "PRIVATE KEY" not in content:
        return None, "This file is not a private key"
    logger.info("browseparc: private key %s read for a Guacamole session", real)
    return content, None


def _guacamole_parameters(protocol):
    """Protocol options configured for the Medulla relay, if any."""
    options = {}
    if not os.path.isfile(GUAC_RELAY_INI):
        return options
    parser = configparser.ConfigParser(interpolation=None)
    try:
        parser.read(GUAC_RELAY_INI)
    except configparser.Error:
        return options
    if not parser.has_section("parameters"):
        return options
    prefix = protocol + "_"
    for key, value in parser.items("parameters"):
        if not key.startswith(prefix):
            continue
        if key in ("%s_username" % protocol, "%s_keyfile" % protocol):
            continue
        options[key[len(prefix):]] = value
    return options


def _guacamole_call(settings, method, path, token=None, payload=None):
    """One REST call against the Guacamole webapp (loopback, short timeout)."""
    url = settings["api"] + path
    data = None
    headers = {}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    if token:
        headers["Guacamole-Token"] = token
    request = urllib.request.Request(url, data=data, headers=headers, method=method)
    context = ssl._create_unverified_context()
    try:
        with urllib.request.urlopen(request, timeout=GUAC_TIMEOUT, context=context) as response:
            return response.status, response.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read().decode("utf-8", "replace")


GUAC_TOKEN_TTL = 300
_GUAC_TOKEN = {"key": None, "token": None, "data_source": None, "time": 0.0}
# One session at a time touches the connections: two clicks on the same machine
# must not both see "no connection yet" and create it twice.
_GUAC_LOCK = threading.Lock()


def _guacamole_token(settings, fresh=False):
    key = (settings["api"], settings["username"])
    now = time.time()
    with _LOCK:
        if (not fresh and _GUAC_TOKEN["key"] == key and _GUAC_TOKEN["token"]
                and now - _GUAC_TOKEN["time"] < GUAC_TOKEN_TTL):
            settings["data_source"] = _GUAC_TOKEN["data_source"] or settings["data_source"]
            return _GUAC_TOKEN["token"]
    payload = urllib.parse.urlencode({"username": settings["username"],
                                      "password": settings["password"]}).encode()
    request = urllib.request.Request(settings["api"] + "/api/tokens", data=payload,
                                     method="POST")
    request.add_header("Content-Type", "application/x-www-form-urlencoded")
    context = ssl._create_unverified_context()
    try:
        with urllib.request.urlopen(request, timeout=GUAC_TIMEOUT, context=context) as response:
            answer = json.loads(response.read().decode("utf-8", "replace"))
    except urllib.error.HTTPError as exc:
        raise ValueError("Guacamole refused the connection (HTTP %s)" % exc.code)
    except Exception as exc:
        raise ValueError("Guacamole unreachable: %s" % exc)
    token = answer.get("authToken")
    if not token:
        raise ValueError("Guacamole did not return any token")
    settings["data_source"] = answer.get("dataSource") or settings["data_source"]
    with _LOCK:
        _GUAC_TOKEN.update(key=key, token=token, data_source=settings["data_source"],
                           time=now)
    return token


def _guacamole_cux_id(connection_id):
    """Client identifier used in the Guacamole URL (see msc/vnc_guacamole.php)."""
    raw = str(connection_id).encode() + b"\x00c\x00mysql"
    return base64.b64encode(raw).decode()


def _public_base_url():
    """Base URL the target machines use to reach this Medulla server.

    Taken from the generic installer Medulla generates (it hardcodes it), with
    the Apache vhost as a fallback.
    """
    installer = os.path.join(CLIENT_ROOT, "win", "install-agent.ps1")
    try:
        with open(installer, "r", encoding="utf-8", errors="replace") as handle:
            found = re.search(r"https?://[^\s'\"]+?/downloads/", handle.read())
        if found:
            return found.group(0)[: -len("/downloads/")]
    except OSError:
        pass
    for path in glob.glob("/etc/apache2/sites-enabled/*"):
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                found = re.search(r"^\s*ServerName\s+(\S+)", handle.read(), re.M)
            if found:
                return "https://%s" % found.group(1)
        except OSError:
            continue
    return "https://127.0.0.1"


# Entity names change rarely: the database is asked at most once per TTL so a
# page load does not open a connection every time (the mmc-agent has a small
# thread pool and php-fpm only 5 workers).
ORG_NAMES_TTL = 600
_ORG_NAMES_CACHE = {"time": 0.0, "names": {}}


def _organisation_names():
    """dl_tag -> friendly name, read only from the admin database."""
    now = time.time()
    with _LOCK:
        if _ORG_NAMES_CACHE["names"] and now - _ORG_NAMES_CACHE["time"] < ORG_NAMES_TTL:
            return _ORG_NAMES_CACHE["names"]

    names = {}
    try:
        from pulse2.database.admin import AdminDatabase
        from sqlalchemy.orm import sessionmaker, scoped_session

        database = AdminDatabase()
        table = getattr(database, "Saas_organisations", None)
        if table is None:
            return names
        session = scoped_session(sessionmaker(bind=database.db))
        try:
            for row in session.query(table.dl_tag, table.organisation_name,
                                     table.entity_name).all():
                if row[0]:
                    names[row[0]] = row[1] or row[2] or row[0]
        finally:
            session.remove()
    except Exception:
        logger.debug("browseparc: organisation names unavailable", exc_info=True)
    else:
        # Only a successful read is cached: a transient failure is retried.
        with _LOCK:
            _ORG_NAMES_CACHE["names"] = names
            _ORG_NAMES_CACHE["time"] = now
    return names


def _file_info(path):
    try:
        stat = os.stat(path)
    except OSError:
        return None
    return {
        "path": path,
        "name": os.path.basename(path),
        "size": stat.st_size,
        "date": time.strftime("%Y-%m-%d %H:%M", time.localtime(stat.st_mtime)),
    }


def _mac_packages(directory):
    """macOS packages (one .pkg per architecture) found in a directory."""
    files = []
    for path in sorted(glob.glob(os.path.join(directory, MAC_AGENT_GLOB))):
        info = _file_info(path)
        if info:
            files.append(info)
    if not files:
        return None
    return {
        "dir": directory,
        "files": [{"name": item["name"], "size": item["size"]} for item in files],
        "date": max(item["date"] for item in files),
    }


def _list_agents():
    """Every agent that can be deployed, entity ones first."""
    base = _public_base_url()
    names = _organisation_names()
    agents = []

    for entry in sorted(glob.glob(os.path.join(AGENT_ROOT, "*"))):
        if not os.path.isdir(entry):
            continue
        dl_tag = os.path.basename(entry)
        windows = _file_info(os.path.join(entry, WIN_AGENT_FILE))
        linux = _file_info(os.path.join(entry, LIN_AGENT_FILE))
        mac = _mac_packages(entry)
        if not windows and not linux and not mac:
            continue
        label = names.get(dl_tag) or ("Agent %s" % dl_tag[:8])
        agent = {
            "id": "entity:%s" % dl_tag,
            "kind": "entity",
            "label": label,
            "dl_tag": dl_tag,
            "windows": None,
            "linux": None,
            "mac": mac,
            "date": (windows or linux or mac)["date"],
        }
        if windows:
            agent["windows"] = {
                "url": "%s%s%s/%s" % (base, AGENT_URL_PREFIX, dl_tag, WIN_AGENT_FILE),
                "referer": base + "/",
                "size": windows["size"],
                "name": windows["name"],
            }
        if linux:
            agent["linux"] = {
                "url": "%s%s%s/%s" % (base, AGENT_URL_PREFIX, dl_tag, LIN_AGENT_FILE),
                "referer": base + "/",
                "path": linux["path"],
                "size": linux["size"],
                "name": linux["name"],
            }
        agents.append(agent)

    # The historical generic agent (install-agent.ps1 for Windows, the script
    # below for Linux). Always proposed, it is the previous behaviour.
    generic_win = os.path.join(CLIENT_ROOT, "win", "install-agent.ps1")
    generic_lin = os.path.join(CLIENT_ROOT, "lin", LIN_AGENT_FILE)
    generic = {
        "id": GENERIC_AGENT_ID,
        "kind": "generic",
        "label": "Agent generique (install-agent.ps1)",
        "dl_tag": None,
        "windows": None,
        "linux": None,
        "mac": _mac_packages(os.path.join(CLIENT_ROOT, "mac")),
        "date": None,
    }
    if os.path.isfile(generic_win):
        info = _file_info(generic_win)
        generic["windows"] = {"script": generic_win, "name": info["name"],
                              "size": info["size"]}
        generic["date"] = info["date"]
    if os.path.isfile(generic_lin):
        info = _file_info(generic_lin)
        generic["linux"] = {"path": generic_lin, "name": info["name"],
                            "size": info["size"],
                            "url": "%s/downloads/lin/%s" % (base, LIN_AGENT_FILE),
                            "referer": ""}
    agents.append(generic)
    return agents



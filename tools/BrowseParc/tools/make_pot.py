#!/usr/bin/env python3
"""Builds locale/browseparc.pot, the translation template of the page.

Every msgid comes from a literal _T('...', 'admin') call of web/*.php. xgettext
is not needed: the template is written like the other Medulla modules do
(admin.pot), with the source references.

    python3 tools/make_pot.py            writes locale/browseparc.pot
    python3 tools/make_pot.py --check    fails when the file is out of date
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CALL = re.compile(r"""_T\(\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*,\s*['"]admin['"]\s*\)""")
HEADER = '''# Translation template of the "Browse my fleet" page (module admin).
# Generated by tools/make_pot.py, do not edit by hand.
msgid ""
msgstr ""
"Project-Id-Version: medulla\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
'''


def unescape(single, double):
    if single is not None:
        return single.replace("\\'", "'").replace("\\\\", "\\")
    return double.replace('\\"', '"').replace("\\\\", "\\")


def collect():
    found = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "web", "*.php"))):
        rel = os.path.relpath(path, ROOT)
        with open(path, encoding="utf-8") as handle:
            for number, line in enumerate(handle, 1):
                for match in CALL.finditer(line):
                    found.setdefault(unescape(match.group(1), match.group(2)), []).append("%s:%d" % (rel, number))
    return found


def quote(text):
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def render(found):
    out = [HEADER]
    for msgid in sorted(found):
        out.append("\n#: %s\n" % " ".join(found[msgid]))
        if re.search(r"%[sd]", msgid):
            out.append("#, php-format\n")
        out.append("msgid %s\nmsgstr \"\"\n" % quote(msgid))
    return "".join(out)


def main():
    target = os.path.join(ROOT, "locale", "browseparc.pot")
    text = render(collect())
    if "--check" in sys.argv:
        current = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        if current != text:
            sys.stderr.write("locale/browseparc.pot is out of date: run tools/make_pot.py\n")
            return 1
        return 0
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(text)
    print("%s: %d messages" % (target, len(collect())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
